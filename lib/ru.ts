export type D = (s: string) => string;

function plural(n: number, one: string, few: string, many: string) {
  const a = n % 100, b = n % 10;
  if (a >= 11 && a <= 14) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

/** Translates a data string. Handles durations, fees and the intake month as well as the dictionary entries. */
export function makeD(lang: Lang): D {
  if (lang !== 'ru') return (s) => s;
  const months: Record<string, string> = { January: 'Январь', February: 'Февраль', March: 'Март', April: 'Апрель', May: 'Май', June: 'Июнь', July: 'Июль', August: 'Август', September: 'Сентябрь', October: 'Октябрь', November: 'Ноябрь', December: 'Декабрь' };
  return (s) => {
    if (RU[s]) return RU[s];
    let m = s.match(/^(\d+) years?$/);
    if (m) return m[1] + ' ' + plural(+m[1], 'год', 'года', 'лет');
    m = s.match(/^(\w+) (\d{4})$/);
    if (m && months[m[1]]) return months[m[1]] + ' ' + m[2];
    if (/ per year$/.test(s)) return s.replace(/ per year$/, ' в год');
    return s;
  };
}
